#!/usr/bin/env python3
"""Shared file helpers for the knowledge scripts.

The scripts here all read and write the same small set of YAML and
Markdown files. This module keeps the parsing, the deterministic YAML
output and the finding-frontmatter handling in one place, so index,
validate_rules, compile_rules, verify_citations and promote agree on
what a finding and a rule file look like.
"""

from __future__ import annotations

import datetime
import hashlib
import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from ruamel.yaml import YAML

CORE_DIR = Path(__file__).resolve().parent.parent
KNOWLEDGE_DIR = CORE_DIR / "knowledge"
RULES_DIR = KNOWLEDGE_DIR / "rules"
FINDINGS_DIR = KNOWLEDGE_DIR / "findings"
QUARANTINE_DIR = KNOWLEDGE_DIR / "quarantine"
GAPS_DIR = KNOWLEDGE_DIR / "gaps"
PLUGIN_JSON = CORE_DIR.parent.parent / ".claude-plugin" / "plugin.json"

FINDING_ID_RE = re.compile(r"^[FL]-[0-9]{4}$")
RULE_ID_RE = re.compile(r"^R-[a-z0-9<>-]+-L?[0-9]{3}$")
TEMPLATE_NAMES = {"_TEMPLATE.yaml", "_TEMPLATE.md"}


def normalize(value: Any) -> Any:
    """Turn YAML dates and times into the strings the schemas expect."""
    if isinstance(value, dict):
        return {str(key): normalize(item) for key, item in value.items()}
    if isinstance(value, list):
        return [normalize(item) for item in value]
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    return value


def yaml_safe() -> YAML:
    return YAML(typ="safe")


def yaml_out() -> YAML:
    """A deterministic round-trip writer: block style, no wrapping."""
    yaml = YAML()
    yaml.default_flow_style = False
    yaml.width = 1000
    yaml.allow_unicode = True
    yaml.indent(mapping=2, sequence=4, offset=2)
    return yaml


def load_yaml(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return normalize(yaml_safe().load(handle))


def yaml_loads(text: str) -> Any:
    return normalize(yaml_safe().load(text))


def dump_yaml(data: Any) -> str:
    from io import StringIO

    stream = StringIO()
    yaml_out().dump(data, stream)
    return stream.getvalue()


def split_frontmatter(text: str) -> Tuple[Optional[str], str]:
    """Return (frontmatter text, body). Frontmatter is None when absent."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, text
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            return "\n".join(lines[1:index]), "\n".join(lines[index + 1 :])
    return None, text


def join_frontmatter(frontmatter: str, body: str) -> str:
    return "---\n{}\n---\n{}".format(frontmatter.rstrip("\n"), body)


def read_frontmatter(path: Path) -> Tuple[Dict[str, Any], str]:
    """Read a Markdown file's YAML frontmatter and return it with the body."""
    text = path.read_text(encoding="utf-8")
    frontmatter, body = split_frontmatter(text)
    if frontmatter is None:
        raise ValueError("no YAML frontmatter")
    data = normalize(yaml_safe().load(frontmatter))
    if not isinstance(data, dict):
        raise ValueError("frontmatter is not a mapping")
    return data, body


def write_frontmatter(path: Path, data: Dict[str, Any], body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(join_frontmatter(dump_yaml(data), body), encoding="utf-8")


def claim_one_line(claim: Any) -> str:
    return " ".join(str(claim).split())


def finding_paths(directory: Path) -> List[Path]:
    """Every finding file in a folder, in a stable order."""
    paths = [
        path
        for path in sorted(directory.glob("*.md"))
        if path.name not in TEMPLATE_NAMES and not path.name.startswith(".")
    ]
    return paths


def rule_paths(directory: Path) -> List[Path]:
    """Every rule file in a folder tree, excluding policies and templates."""
    paths = []
    for path in sorted(directory.rglob("*.yaml")):
        if path.name in TEMPLATE_NAMES or path.name == "policies.yaml":
            continue
        paths.append(path)
    return paths


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def write_if_changed(path: Path, text: str) -> bool:
    """Write text only when the bytes differ. Returns True when it wrote."""
    data = text.encode("utf-8")
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def generated_header(tool: str) -> str:
    return "# Generated by scripts/{}. Do not edit by hand.\n".format(tool)


def plugin_version(override: Optional[str] = None) -> str:
    if override:
        return override
    with PLUGIN_JSON.open("r", encoding="utf-8") as handle:
        return json.load(handle)["version"]


def next_free(numbers: List[int], start: int = 1) -> int:
    used = {number for number in numbers}
    candidate = start
    while candidate in used:
        candidate += 1
    return candidate


def unique_path(directory: Path, name: str) -> Path:
    """A path in directory that does not overwrite an existing file."""
    candidate = directory / name
    if not candidate.exists():
        return candidate
    stem = Path(name).stem
    suffix = Path(name).suffix
    counter = 2
    while True:
        candidate = directory / "{}.{}{}".format(stem, counter, suffix)
        if not candidate.exists():
            return candidate
        counter += 1
