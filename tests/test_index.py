"""The generated index is ordered, one entry per finding, and idempotent."""

import support
import index


def test_index_is_deterministic_and_second_run_changes_no_byte(tmp_path, capsys):
    findings = tmp_path / "findings"
    support.write_finding(
        findings,
        support.finding(
            "F-0002",
            claim="A second claim that\nspans two lines.",
            direction=None,
            scopes=["age/high-school"],
            grade="C",
        ),
    )
    support.write_finding(findings, support.finding("F-0001"))

    assert index.main(["--findings", str(findings)]) == 0
    out = findings / "index.yaml"
    first = out.read_bytes()
    assert b"Generated by scripts/index.py" in first

    assert index.main(["--findings", str(findings)]) == 0
    assert out.read_bytes() == first
    assert "unchanged" in capsys.readouterr().out

    data = support.files.load_yaml(out)
    assert [entry["id"] for entry in data["findings"]] == ["F-0001", "F-0002"]
    assert data["findings"][1]["claim"] == "A second claim that spans two lines."
    assert data["findings"][1]["scopes"] == ["age/high-school"]


def test_index_refuses_a_finding_without_a_status(tmp_path):
    findings = tmp_path / "findings"
    data = support.finding("F-0001")
    del data["status"]
    support.write_finding(findings, data)
    assert index.main(["--findings", str(findings)]) == 1
    assert not (findings / "index.yaml").exists()


def test_index_sorts_numerically_not_lexically(tmp_path):
    findings = tmp_path / "findings"
    for number in (10, 2, 1):
        support.write_finding(findings, support.finding("F-{:04d}".format(number)))
    assert index.main(["--findings", str(findings)]) == 0
    data = support.files.load_yaml(findings / "index.yaml")
    assert [entry["id"] for entry in data["findings"]] == [
        "F-0001",
        "F-0002",
        "F-0010",
    ]
